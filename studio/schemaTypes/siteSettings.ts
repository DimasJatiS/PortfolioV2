import { defineArrayMember, defineField, defineType } from "sanity";

export const siteSettings = defineType({
  name: "siteSettings",
  title: "Site settings",
  type: "document",
  groups: [
    { name: "identity", title: "Identity", default: true },
    { name: "availability", title: "Availability" },
    { name: "contact", title: "CV & contact" },
    { name: "about", title: "About" },
    { name: "seo", title: "SEO" },
  ],
  fields: [
    defineField({
      name: "name",
      title: "Name",
      type: "string",
      group: "identity",
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: "role",
      title: "Role",
      description: "Shown consistently on every page, e.g. Software Engineer.",
      type: "string",
      group: "identity",
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: "headline",
      title: "Headline",
      description: "LONG LIVE LEARNER",
      type: "localeString",
      group: "identity",
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: "statement",
      title: "Hero statement",
      description: "Wrap one word in *asterisks* to set it in the italic serif accent.",
      type: "localeString",
      group: "identity",
    }),
    defineField({
      name: "manifesto",
      title: "Manifesto",
      description: "3–5 lines for the Ascent act on Home.",
      type: "array",
      group: "identity",
      of: [defineArrayMember({ type: "localeString" })],
      validation: (rule) => rule.min(3).max(5),
    }),
    defineField({
      name: "bioShort",
      title: "Short bio (about 50 words)",
      type: "localeText",
      group: "about",
    }),
    defineField({
      name: "bioLong",
      title: "Long bio (about 200 words)",
      type: "localeText",
      group: "about",
    }),
    defineField({
      name: "interests",
      title: "Interests",
      description: "Beyond code: Web3, renewable energy, event management.",
      type: "array",
      group: "about",
      of: [defineArrayMember({ type: "localeString" })],
    }),
    defineField({
      name: "currentlyLearning",
      title: "Currently learning",
      type: "array",
      group: "about",
      of: [defineArrayMember({ type: "localeString" })],
    }),
    defineField({
      name: "showAvailability",
      title: "Show the internship availability label",
      description: "Turn off to hide the label everywhere without changing the layout.",
      type: "boolean",
      group: "availability",
      initialValue: true,
    }),
    defineField({
      name: "availability",
      title: "Availability",
      type: "object",
      group: "availability",
      fields: [
        defineField({
          name: "startMonth",
          title: "Start month",
          description: "Pick any day in the starting month.",
          type: "date",
        }),
        defineField({
          name: "minMonths",
          title: "Minimum duration (months)",
          type: "number",
          validation: (rule) => rule.integer().positive(),
        }),
        defineField({
          name: "mode",
          title: "Work mode",
          type: "string",
          options: {
            list: [
              { title: "Onsite", value: "onsite" },
              { title: "Remote", value: "remote" },
              { title: "Onsite or remote", value: "both" },
            ],
            layout: "radio",
          },
        }),
      ],
    }),
    defineField({
      name: "cv",
      title: "CV (PDF)",
      description: "English, at most 500 KB. Powers every Download CV button.",
      type: "file",
      group: "contact",
      options: { accept: "application/pdf" },
    }),
    defineField({
      name: "socials",
      title: "Contact links",
      description: "Email, LinkedIn and GitHub only. Never add a phone number.",
      type: "array",
      group: "contact",
      of: [
        defineArrayMember({
          type: "object",
          name: "social",
          fields: [
            defineField({
              name: "platform",
              title: "Platform",
              type: "string",
              options: {
                list: [
                  { title: "Email", value: "email" },
                  { title: "LinkedIn", value: "linkedin" },
                  { title: "GitHub", value: "github" },
                ],
              },
              validation: (rule) => rule.required(),
            }),
            defineField({
              name: "url",
              title: "URL",
              description: "For email use mailto:you@example.com",
              type: "url",
              validation: (rule) => rule.required().uri({ scheme: ["https", "mailto"] }),
            }),
          ],
          preview: { select: { title: "platform", subtitle: "url" } },
        }),
      ],
      validation: (rule) => rule.unique(),
    }),
    defineField({
      name: "seo",
      title: "Default SEO",
      type: "object",
      group: "seo",
      fields: [
        defineField({ name: "title", title: "Title", type: "localeString" }),
        defineField({ name: "description", title: "Description", type: "localeText" }),
        defineField({
          name: "ogImage",
          title: "Default share image",
          type: "image",
          options: { hotspot: true },
        }),
      ],
    }),
  ],
  preview: { prepare: () => ({ title: "Site settings" }) },
});
